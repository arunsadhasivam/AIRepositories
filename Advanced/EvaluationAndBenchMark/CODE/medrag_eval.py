# medrag_eval.py
# MedRAG — Medical Retrieval-Augmented Generation benchmark.
# Evaluates retrieval quality against medical corpora:
# PubMed abstracts, medical textbooks, clinical guidelines.
# Measures whether the correct medical source was retrieved and used.
# Results are logged to Langfuse via the centralised tracker.
#
# MedRAG GitHub: https://github.com/Teddy-XiongGZ/MedRAG
# Install: pip install medrag (or clone from GitHub)

from tracking.langfuse_tracker import create_trace, log_score   # centralised Langfuse logging


# ---------------------------------------------------------------------------
# MedRAG corpus options — each represents a different medical knowledge source.
# In production, MedRAG retrieves from these corpora automatically.
# ---------------------------------------------------------------------------
MEDRAG_CORPORA = {
    "pubmed"      : "PubMed abstracts — 30M+ biomedical research papers",
    "textbooks"   : "Medical textbooks — Harrison's, Robbins, etc.",
    "guidelines"  : "Clinical practice guidelines — CDC, AAP, WHO"
}


# ---------------------------------------------------------------------------
# Sample MedRAG-style evaluation data.
# In real usage, MedRAG fetches questions from its benchmark and retrieves
# from the corpus automatically. This sample simulates that output.
# ---------------------------------------------------------------------------
SAMPLE_MEDRAG_DATA = [
    {
        "corpus": "pubmed",
        # Clinical question from the MedRAG benchmark
        "question": "What is the first-line antibiotic treatment for community-acquired pneumonia in children?",
        # Answer generated by your RAG pipeline using retrieved PubMed chunks
        "rag_answer": "Amoxicillin is the first-line treatment for community-acquired pneumonia in children.",
        # Ground truth from MedRAG benchmark
        "gold_answer": "Amoxicillin",
        # Retrieved PubMed snippets
        "retrieved_snippets": [
            "Amoxicillin remains the recommended first-line antibiotic for community-acquired pneumonia (CAP) in children per AAP guidelines.",
            "For children with non-severe CAP, high-dose amoxicillin (90 mg/kg/day) is preferred over broader-spectrum antibiotics."
        ],
        # Correct source document that should have been retrieved
        "gold_source": "AAP guidelines on pediatric pneumonia management"
    },
    {
        "corpus": "textbooks",
        "question": "What is the mechanism of action of palivizumab?",
        "rag_answer": "Palivizumab is a monoclonal antibody that binds to the RSV F protein, preventing viral fusion with host cells.",
        "gold_answer": "Monoclonal antibody targeting RSV F protein",
        "retrieved_snippets": [
            "Palivizumab is a humanised monoclonal antibody directed against the F (fusion) protein of RSV, inhibiting viral entry into host cells."
        ],
        "gold_source": "Nelson Textbook of Pediatrics — RSV chapter"
    }
]


def compute_answer_match(rag_answer: str, gold_answer: str) -> float:
    """
    Check if the gold answer is contained within the RAG pipeline answer.
    Case-insensitive substring match — appropriate for medical term matching.

    Args:
        rag_answer : Answer produced by RAG pipeline.
        gold_answer: Correct answer from MedRAG benchmark.

    Returns:
        1.0 if gold answer found in RAG answer, 0.0 otherwise.
    """
    return 1.0 if gold_answer.strip().lower() in rag_answer.strip().lower() else 0.0


def compute_source_coverage(retrieved_snippets: list, gold_source: str) -> float:
    """
    Check if any retrieved snippet references the correct source document.
    Simulates source attribution quality — critical for clinical RAG.

    Args:
        retrieved_snippets: List of text chunks retrieved from the corpus.
        gold_source       : The correct source document name.

    Returns:
        Coverage score between 0.0 and 1.0.
    """
    # Extract key terms from gold source for flexible matching
    gold_keywords = [word.lower() for word in gold_source.split() if len(word) > 3]

    matched_keywords = 0  # count how many gold keywords appear in retrieved snippets

    for snippet in retrieved_snippets:
        snippet_lower = snippet.lower()
        for keyword in gold_keywords:
            if keyword in snippet_lower:
                matched_keywords += 1  # this keyword was found in a retrieved chunk

    # Coverage = fraction of gold keywords found across all retrieved snippets
    coverage = matched_keywords / len(gold_keywords) if gold_keywords else 0.0
    return min(coverage, 1.0)  # cap at 1.0


def run_medrag_benchmark(data: list = None) -> dict:
    """
    Run MedRAG offline benchmark evaluation across medical corpora.

    Computes per sample:
        - Answer Match Score   : did RAG answer contain the gold answer?
        - Source Coverage Score: did retrieved snippets cover the correct source?

    Args:
        data: List of MedRAG-format dicts. Defaults to SAMPLE_MEDRAG_DATA.

    Returns:
        Dict with aggregate scores: avg_answer_match, avg_source_coverage.
    """
    eval_data = data or SAMPLE_MEDRAG_DATA

    answer_match_scores = []    # collect answer match scores across all samples
    source_coverage_scores = [] # collect source coverage scores across all samples

    for item in eval_data:
        # Compute answer match for this sample
        answer_score = compute_answer_match(item["rag_answer"], item["gold_answer"])

        # Compute source coverage for this sample
        coverage_score = compute_source_coverage(item["retrieved_snippets"], item["gold_source"])

        answer_match_scores.append(answer_score)
        source_coverage_scores.append(coverage_score)

        # Create a Langfuse trace per benchmark question
        trace = create_trace(
            query=item["question"],
            metadata={"evaluator": "MedRAG", "corpus": item["corpus"]}
        )

        # Log answer match score to Langfuse
        log_score(
            trace_id=trace.id,
            metric_name="medrag_answer_match",
            score=answer_score,
            comment=f"MedRAG [{item['corpus']}] — rag='{item['rag_answer'][:50]}' gold='{item['gold_answer']}'"
        )

        # Log source coverage score to Langfuse
        log_score(
            trace_id=trace.id,
            metric_name="medrag_source_coverage",
            score=coverage_score,
            comment=f"MedRAG [{item['corpus']}] source coverage vs '{item['gold_source']}'"
        )

        print(f"\n[MedRAG] Corpus: {item['corpus']}")
        print(f"  Question       : {item['question'][:80]}...")
        print(f"  Answer Match   : {answer_score} | Source Coverage: {coverage_score:.4f}")

    # Compute aggregate averages
    avg_answer = sum(answer_match_scores) / len(answer_match_scores)
    avg_coverage = sum(source_coverage_scores) / len(source_coverage_scores)

    print(f"\n[MedRAG] Aggregate — Avg Answer Match: {avg_answer:.4f} | Avg Source Coverage: {avg_coverage:.4f}")

    return {
        "avg_answer_match": avg_answer,
        "avg_source_coverage": avg_coverage
    }


# ---------------------------------------------------------------------------
# Entry point — run directly to test with sample data
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    run_medrag_benchmark()
